import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const base = 'payload/node/workloads/private-services/';
for (const name of ['pocket-id', 'netbird-server', 'netbird-dashboard']) {
  const unit = read(`${base}${name}.container`);
  assert.match(unit, /^Image=localhost\/gnx\/[^@]+@sha256:[a-f0-9]{64}$/m);
  assert.match(unit, /^Pull=never$/m);
  assert.match(unit, /^User=10001:/m);
  assert.match(unit, /^DropCapability=all$/m);
  assert.match(unit, /^NoNewPrivileges=true$/m);
  assert.doesNotMatch(unit, /PublishPort=|privileged|Image=.*:latest/);
}
const server = read(`${base}netbird-server.container`);
assert.match(server, /NB_DISABLE_GEOLOCATION=true/);
assert.match(server, /SSL_CERT_FILE=\/etc\/gnx\/gateway-ca.pem/);
assert.match(server, /DNS=GNX_GATEWAY_IP/);
assert.match(server, /127\.0\.0\.1\/8081/);
assert.match(server, /GET \/api\/instance HTTP\/1\.0/);
assert.match(read('payload/node/gateway/routes.conf'), /reverse_proxy h2c:\/\/netbird\.mesh\.gnx:8081 \{\s+transport http \{\s+versions h2c 1\.1/);
const dashboard = read(`${base}netbird-dashboard.container`);
assert.match(dashboard, /AUTH_AUTHORITY=https:\/\/netbird.gnx\/oauth2/);
assert.match(dashboard, /Environment="AUTH_SUPPORTED_SCOPES=openid profile email groups"/);
assert.match(dashboard, /AUTH_REDIRECT_URI=\/nb-auth/);
const pocket = read(`${base}pocket-id.container`);
assert.match(pocket, /HOST=0\.0\.0\.0/);
assert.match(pocket, /\/usr\/bin\/wget/);
const config = read(`${base}netbird-config.run`);
assert.match(config, /openssl rand -base64 32/);
assert.match(config, /listenAddress: ":8081"/);
assert.match(config, /issuer: "https:\/\/netbird.gnx\/oauth2"/);
assert.match(config, /stunPorts: \[3478\]/);
assert.doesNotMatch(config, /^source /m);
const enroll = read(`${base}access-enroll.run`);
assert.match(enroll, /NETBIRD_EXISTING_OWNER_REQUIRES_ENROLLMENT/);
assert.match(enroll, /stat\.S_IMODE\(st\.st_mode\) != 0o600/);
assert.match(enroll, /'type': 'pocketid'/);
assert.match(enroll, /https:\/\/netbird.gnx\/oauth2\/callback/);
assert.match(enroll, /'pat_expire_in': 1/);
assert.doesNotMatch(enroll, /print\((state|token|password|secret)/);
const verify = read('payload/node/compute/access-verify.run');
for (const check of ['pocket_oidc_https', 'netbird_oidc_https', 'netbird_dashboard_https', 'netbird_management_grpc', 'netbird_signal_grpc', 'netbird_relay_websocket', 'netbird_stun']) assert.ok(verify.includes(check));
assert.match(verify, /ssl.create_default_context/);
assert.doesNotMatch(verify, /CERT_NONE|check_hostname\s*=\s*False/);
const stun = read('payload/node/compute/netbird-stun.run');
assert.match(stun, /iifname "tailscale0" ip daddr \$node udp dport 3478/);
assert.doesNotMatch(stun, /eth0.*3478|flush ruleset|node=\$\(ip /);
assert.match(stun, /node=\$\(\/usr\/bin\/podman exec gnx-mesh tailscale ip -4\)/);
const policy = read('payload/node/compute/access-mesh-policy.run');
assert.match(policy, /ACCESS_MESH_POLICY_REQUIRED/);
assert.match(policy, /PacketFilterRules/);
assert.match(policy, /protocol not in protocols/);
assert.doesNotMatch(policy, /requests\.|\.put\(|\.post\(/);
const reconcile = read('payload/node/compute/reconcile-access.run');
assert.ok(reconcile.indexOf('access-mesh-policy.run"\n  bash') >= 0);
assert.match(read('payload/node/verify.run'), /if python3 "\$runtime_dir\/access-mesh-policy.run"; then/);
assert.match(read(`${base}install.run`), /OFFLINE_BUNDLE_DIGEST_INVALID/);
const html = read('apps/web-app/index.html');
assert.match(html, /https:\/\/pocket.gnx/);
assert.match(html, /https:\/\/netbird.gnx/);
console.log('Pocket ID / combined NetBird / dashboard contracts passed; not a passkey or live peer proof.');
