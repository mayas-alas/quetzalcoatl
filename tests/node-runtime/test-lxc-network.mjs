import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const read = path => readFileSync(new URL(`../../${path}`, import.meta.url), 'utf8');
const network = read('payload/node/compute/network.run');
const guest = read('payload/node/compute/eth0.network');
const service = read('payload/node/compute/gnx-lxc-network.service');
const compute = read('payload/node/services/compute.container');
const install = read('payload/node/install.run');
const upgrade = read('apps/host-agent/src/linux_node.rs');
const lxc = read('payload/node/compute/lxc.run');
const guard = read('payload/node/workloads/rustfs/mesh.nft');
assert.match(guest, /Name=eth0/);
assert.match(guest, /DHCP=ipv4/);
assert.match(guest, /UseDNS=no/);
const guestSetup = read('payload/node/compute/guest-network.run');
assert.match(guestSetup, /systemctl disable --now networking.service/);
assert.match(guestSetup, /GUEST_DHCP_TIMEOUT/);
assert.match(network, /onboot: 1/);
assert.match(network, /table netdev gnx_lxc_transport/);
assert.match(network, /hook ingress device "veth\$\{vmid\}i0" priority -500/);
assert.doesNotMatch(network, /devices =/);
assert.match(network, /iifname @blocked counter drop/);
assert.match(compute, /Volume=\/usr\/sbin\/nft:\/usr\/sbin\/nft:ro/);
assert.ok(network.indexOf('transport close "$vmid"') < network.indexOf('sysctl -w'));
assert.ok(network.indexOf('transport close "$vmid"', network.indexOf('# Existing managed')) < network.indexOf('pct start "$vmid"'));
assert.ok(guestSetup.indexOf('gnx-workload-mesh guard') < guestSetup.indexOf('systemctl restart systemd-networkd'));
assert.match(network, /pct stop "\$vmid"/);
assert.match(network, /TRANSPORT_GATE_UNAVAILABLE/);
assert.match(read('payload/node/compute/pve-guests-gnx.conf'), /Requires=gnx-lxc-network.service/);
assert.match(compute, /pve-guests.service.d:ro,Z/);
assert.match(install, /compute\/install-network.run/);
assert.match(network, /iptables -w -t "\$table" -C/);
assert.match(network, /GNX_LXC_DHCP/);
assert.match(network, /--ctstate ESTABLISHED,RELATED/);
assert.match(network, /GNX_LXC_NAT -j MASQUERADE/);
assert.match(network, /tags: .*gnx-rustfs/);
assert.doesNotMatch(network, /iptables .*-(?:F|X)\b|systemctl (?:stop|disable|mask) pve-firewall/);
assert.match(service, /After=.*dnsmasq.service pve-firewall.service/);
assert.match(service, /Before=.*pve-guests.service/);
assert.match(compute, /compute-network:\/etc\/gnx\/network:ro,Z/);
assert.match(compute, /gnx-lxc-network.service:ro,Z/);
assert.match(compute, /pve-firewall.service.d:ro,Z/);
const firewall = read('payload/node/compute/pve-firewall-gnx.conf');
assert.match(firewall, /--set ip6tables \/usr\/sbin\/ip6tables-nft/);
assert.match(firewall, /--set ebtables \/usr\/sbin\/ebtables-nft/);
assert.doesNotMatch(firewall, /--set iptables /);
assert.match(install, /compute\/install-network.run/);
assert.match(upgrade, /compute\/install-network.run/);
assert.match(lxc, /GUEST_DHCP_TIMEOUT/);
assert.match(lxc, /network.run close "\$vmid"/);
assert.ok(lxc.indexOf('network.run close "$vmid"', lxc.indexOf('provision()')) < lxc.indexOf('pct create "$vmid"'));
assert.match(lxc, /gnx-install-rustfs --prepare/);
assert.equal((lxc.match(/configure_network "\$vmid"/g) || []).length, 3);
assert.match(guard, /oifname "eth0" udp sport 68 udp dport 67 accept/);
assert.match(guard, /iifname "eth0" udp sport 67 udp dport 68 accept/);
assert.match(guard, /policy drop/);
console.log('LXC build/boot/upgrade network contracts passed');
